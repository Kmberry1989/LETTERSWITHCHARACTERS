import { readFileSync, writeFileSync } from 'node:fs';

const [allowedPath, answersPath] = process.argv.slice(2);
if (!allowedPath || !answersPath) {
  throw new Error('Usage: node scripts/generate-five-in-six-guesses.mjs <allowed-guesses.txt> <answers.txt>');
}

const currentSource = readFileSync('src/lib/arcade/five-in-six-words.ts', 'utf8');
const currentWords = currentSource.match(/`([\s\S]*?)`/)?.[1]?.trim().split(/\s+/) || [];
const sourceWords = [
  ...readFileSync(allowedPath, 'utf8').trim().split(/\s+/),
  ...readFileSync(answersPath, 'utf8').trim().split(/\s+/),
  ...currentWords,
];
const words = [...new Set(sourceWords.map((word) => word.toLowerCase()).filter((word) => /^[a-z]{5}$/.test(word)))].sort();
const lines = [];
for (let index = 0; index < words.length; index += 18) {
  lines.push(words.slice(index, index + 18).join(' '));
}

writeFileSync(
  'src/lib/arcade/five-in-six-guesses.ts',
  `// Generated by scripts/generate-five-in-six-guesses.mjs. See src/lib/arcade/FIVE_IN_SIX_WORDS_SOURCE.md.\n` +
    `const RAW_FIVE_IN_SIX_GUESSES = \`\n${lines.join('\n')}\n\`;\n\n` +
    `export const FIVE_IN_SIX_GUESSES = RAW_FIVE_IN_SIX_GUESSES.trim().split(/\\s+/) as readonly string[];\n` +
    `export const FIVE_IN_SIX_GUESS_SET = new Set(FIVE_IN_SIX_GUESSES);\n`
);

console.log(`Generated ${words.length.toLocaleString()} accepted five-letter guesses.`);
